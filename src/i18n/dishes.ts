export const dishDictionaryOptions = Object.keys(dishTranslations)
  .sort((left, right) => left.localeCompare(right))
  .map((value) => ({
    value,
    arabic: dishTranslations[value],
  }));

export const translateDishLabel = (
  value?: string | null,
  language?: string,
  arabicValue?: string | null
): string => {
  const fallback = (value || '').trim();
  const directArabic = (arabicValue || '').trim();

  if (!fallback && !directArabic) {
    return '';
  }

  const normalizedLanguage = normalizeLanguage(language);

  if (normalizedLanguage !== 'ar') {
    return fallback || directArabic;
  }

  if (directArabic) {
    return directArabic;
  }

  return dishTranslations[normalizeDishKey(fallback)] || fallback;
};
