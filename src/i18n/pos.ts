// Explicit English fallback keeps old/incomplete locale resources usable without
// changing stored complaint codes or financial calculations.
export const getEnglishPosText = (key: string, values: Record<string, string | number> = {}): string => {
  let current: unknown = posTranslations.en;
  for (const part of key.split('.')) {
    current = current && typeof current === 'object' ? (current as Record<string, unknown>)[part] : undefined;
  }
  return typeof current === 'string'
    ? current.replace(/\{\{(\w+)\}\}/g, (match, name: string) => name in values ? String(values[name]) : match)
    : typeof values.defaultValue === 'string' ? values.defaultValue : key;
};
